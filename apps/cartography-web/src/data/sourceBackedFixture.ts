function relation(
  edge_id: string,
  relation_type: string,
  source_node_id: string,
  target_node_id: string,
  explanation: string,
): GraphEdge {
  return {
    edge_id,
    relation_type,
    source_node_id,
    target_node_id,
    directionality: 'DIRECTED',
    explanation,
  };
}

